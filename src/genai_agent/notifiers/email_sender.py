from __future__ import annotations

import logging
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText

import httpx
import markdown

from genai_agent.config import AgentConfig

logger = logging.getLogger(__name__)


def render_email_html(markdown_content: str, title: str) -> str:
    """Convert Markdown digest into a clean, readable HTML email."""
    body_html = markdown.markdown(
        markdown_content,
        extensions=["extra", "sane_lists", "nl2br"],
    )
    return f"""<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>{title}</title>
</head>
<body style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; line-height: 1.6; color: #1f2937; max-width: 740px; margin: 0 auto; padding: 24px; background-color: #f9fafb;">
  <div style="background-color: #ffffff; border: 1px solid #e5e7eb; border-radius: 10px; padding: 28px;">
    {body_html}
  </div>
  <p style="font-size: 12px; color: #6b7280; text-align: center; margin-top: 16px;">
    Generated by your Autonomous Generative AI Learning Agent (powered by Google Gemini)
  </p>
</body>
</html>"""


def _send_via_smtp(config: AgentConfig, subject: str, markdown_content: str, html_content: str) -> bool:
    if not (config.smtp_host and config.email_from and config.email_to):
        logger.warning("Incomplete SMTP settings (host/from/to); skipping email notification.")
        return False

    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"] = config.email_from
    msg["To"] = config.email_to

    msg.attach(MIMEText(markdown_content, "plain", "utf-8"))
    msg.attach(MIMEText(html_content, "html", "utf-8"))

    recipients = [r.strip() for r in config.email_to.split(",") if r.strip()]

    try:
        if config.smtp_port == 465:
            with smtplib.SMTP_SSL(config.smtp_host, config.smtp_port, timeout=20) as server:
                if config.smtp_username and config.smtp_password:
                    server.login(config.smtp_username, config.smtp_password)
                server.sendmail(config.email_from, recipients, msg.as_string())
        else:
            with smtplib.SMTP(config.smtp_host, config.smtp_port, timeout=20) as server:
                server.ehlo()
                server.starttls()
                server.ehlo()
                if config.smtp_username and config.smtp_password:
                    server.login(config.smtp_username, config.smtp_password)
                server.sendmail(config.email_from, recipients, msg.as_string())
        return True
    except Exception as exc:
        logger.error("Failed to send email via SMTP: %s", exc)
        return False


def _send_via_resend(config: AgentConfig, subject: str, markdown_content: str, html_content: str) -> bool:
    if not (config.resend_api_key and config.email_from and config.email_to):
        logger.warning("Incomplete Resend settings (api_key/from/to); skipping email notification.")
        return False

    recipients = [r.strip() for r in config.email_to.split(",") if r.strip()]
    payload = {
        "from": config.email_from,
        "to": recipients,
        "subject": subject,
        "text": markdown_content,
        "html": html_content,
    }
    try:
        with httpx.Client(timeout=20.0) as client:
            resp = client.post(
                "https://api.resend.com/emails",
                headers={
                    "Authorization": f"Bearer {config.resend_api_key}",
                    "Content-Type": "application/json",
                },
                json=payload,
            )
            resp.raise_for_status()
        return True
    except Exception as exc:
        logger.error("Failed to send email via Resend API: %s", exc)
        return False


def send_email_digest(config: AgentConfig, subject: str, markdown_content: str) -> bool:
    """Send the digest via Email (SMTP or Resend API)."""
    html_content = render_email_html(markdown_content, title=subject)
    if config.email_provider == "resend":
        return _send_via_resend(config, subject, markdown_content, html_content)
    return _send_via_smtp(config, subject, markdown_content, html_content)
